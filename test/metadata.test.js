test('PrusaSlicer G-code: time, filament, temperatures, layer count and thumbnail', () => {
  const thumb = PNG.toString('base64');
  const file = write(
    'prusa.gcode',
    [
      '; generated by PrusaSlicer 2.8.0+win64 on 2026-01-01',
      `; thumbnail begin 16x16 ${thumb.length}`,
      `; ${thumb}`,
      '; thumbnail end',
      'M140 S65',
      'M104 S220',
      ';LAYER_CHANGE',
      ';Z:0.2',
      'G1 X1 Y1 E1',
      ';LAYER_CHANGE',
      ';Z:10',
      'G1 X2 Y2 E2',
      '; filament used [mm] = 1500.5',
      '; filament used [g] = 4.47',
      '; estimated printing time (normal mode) = 1h 5m 0s',
      '; filament_type = PETG;PLA',
      '; layer_height = 0.2',
      '; nozzle_diameter = 0.4,0.4',
      '; printer_model = MK4S',
    ].join('\n'),
  );
  const { meta, thumbnail } = extractMetadata(file, 'prusa.gcode');
  assert.equal(meta.slicer, 'PrusaSlicer 2.8.0+win64');
  assert.equal(meta.estimatedTime, 3900);
  assert.equal(meta.filamentLengthMm, 1500.5);
  assert.equal(meta.filamentWeightG, 4.47);
  assert.equal(meta.filamentType, 'PETG');
  assert.equal(meta.nozzleDiameter, 0.4);
  assert.equal(meta.printerModel, 'MK4S');
  assert.equal(meta.nozzleTemp, 220);
  assert.equal(meta.bedTemp, 65);
  assert.equal(meta.maxZ, 10);
  assert.equal(meta.layerCount, 50);
  assert.equal(thumbnail.mime, 'image/png');
  assert.deepEqual(thumbnail.buffer, PNG);
});

