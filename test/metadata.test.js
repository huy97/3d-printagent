test('Unsliced 3MF: size, volume and overhang measured through the build item transform', () => {
  // A 10x20x30 box sits in its own object file; the build item rotates it 90 degrees about Z and moves it to the bed center.
  const corners = [[0, 0, 0], [10, 0, 0], [10, 20, 0], [0, 20, 0], [0, 0, 30], [10, 0, 30], [10, 20, 30], [0, 20, 30]];
  const faces = [[0, 2, 1], [0, 3, 2], [4, 5, 6], [4, 6, 7], [0, 1, 5], [0, 5, 4], [3, 7, 6], [3, 6, 2], [0, 4, 7], [0, 7, 3], [1, 2, 6], [1, 6, 5]];
  const objectModel = `<model><resources><object id="1" type="model"><mesh>
    <vertices>${corners.map(([x, y, z]) => `<vertex x="${x}" y="${y}" z="${z}"/>`).join('')}</vertices>
    <triangles>${faces.map(([a, b, c]) => `<triangle v1="${a}" v2="${b}" v3="${c}"/>`).join('')}</triangles>
  </mesh></object></resources></model>`;
  const rootModel = `<model><resources>
    <object id="2" type="model"><components><component p:path="/3D/Objects/object_1.model" objectid="1"/></components></object>
  </resources><build>
    <item objectid="2" transform="0 1 0 -1 0 0 0 0 1 128 128 0"/>
  </build></model>`;

  const file = write('cube.3mf', makeZip({ '3D/3dmodel.model': rootModel, '3D/Objects/object_1.model': objectModel }));
  const { meta } = extractMetadata(file, 'cube.3mf');
  assert.equal(meta.sliced, false);
  assert.equal(meta.triangles, 12);
  // The 90 degree Z rotation swaps the X and Y edges, the height stays.
  assert.deepEqual(meta.size, { x: 20, y: 10, z: 30 });
  assert.equal(meta.volumeCm3, 6);
  assert.equal(meta.overhangRatio, 0);
});

const MESH_CORNERS = [[0, 0, 0], [10, 0, 0], [10, 10, 0], [0, 10, 0], [0, 0, 10], [10, 0, 10], [10, 10, 10], [0, 10, 10]];
const MESH_FACES = [[0, 2, 1], [0, 3, 2], [4, 5, 6], [4, 6, 7], [0, 1, 5], [0, 5, 4], [3, 7, 6], [3, 6, 2], [0, 4, 7], [0, 7, 3], [1, 2, 6], [1, 6, 5]];

function cubeObject(id) {
  return `<object id="${id}" type="model"><mesh>
    <vertices>${MESH_CORNERS.map(([x, y, z]) => `<vertex x="${x}" y="${y}" z="${z}"/>`).join('')}</vertices>
    <triangles>${MESH_FACES.map(([a, b, c]) => `<triangle v1="${a}" v2="${b}" v3="${c}"/>`).join('')}</triangles>
  </mesh></object>`;
}

function platedFile(name) {
  const model = `<model><resources>${cubeObject(1)}${cubeObject(2)}</resources><build>
    <item objectid="1" transform="1 0 0 0 1 0 0 0 1 20 30 0"/>
    <item objectid="2" transform="1 0 0 0 1 0 0 0 1 60 60 0"/>
  </build></model>`;
  const settings = `<config>
    <object id="1"><metadata key="name" value="Block A"/></object>
    <object id="2"><metadata key="name" value="Block B"/></object>
    <plate><metadata key="plater_id" value="1"/><model_instance><metadata key="object_id" value="1"/></model_instance></plate>
    <plate><metadata key="plater_id" value="2"/><model_instance><metadata key="object_id" value="2"/></model_instance></plate>
  </config>`;
  return write(
    name,
    makeZip({
      '3D/3dmodel.model': model,
      'Metadata/model_settings.config': settings,
      'Metadata/project_settings.config': JSON.stringify({
        printable_area: ['0x0', '180x0', '180x180', '0x180'],
        printable_height: '180',
        printer_model: 'Bambu Lab A1 mini',
      }),
      'Metadata/plate_1.json': JSON.stringify({ bbox_all: [20, 30, 30, 40], bbox_objects: [] }),
      'Metadata/plate_2.json': JSON.stringify({ bbox_all: [60, 60, 70, 70], bbox_objects: [] }),
    }),
  );
}

test('A zip64-written 3MF still yields geometry instead of reading as empty', () => {
  const model = `<model><resources>${cubeObject(1)}</resources><build><item objectid="1"/></build></model>`;
  const file = write('zip64.3mf', makeZip64({ '[Content_Types].xml': '<Types/>', '3D/3dmodel.model': model }));

  const mesh = readPlateMesh(file, 'zip64.3mf', 1);
  assert.equal(mesh.objects.length, 1);
  assert.equal(mesh.objects[0].triangles, 12);
  assert.deepEqual(mesh.objects[0].bbox, [0, 0, 0, 10, 10, 10]);

  const { meta } = extractMetadata(file, 'zip64.3mf');
  assert.equal(meta.triangles, 12);
  assert.deepEqual(meta.size, { x: 10, y: 10, z: 10 });
});

test('Plate mesh: coordinates already transformed, names from model_settings, each plate returns only its own objects', () => {
  const file = platedFile('plated.3mf');

  const first = readPlateMesh(file, 'plated.3mf', 1);
  assert.equal(first.plate, 1);
  assert.deepEqual(first.plates, [1, 2]);
  assert.equal(first.bed.model, 'Bambu Lab A1 mini');
  assert.deepEqual([first.bed.maxX, first.bed.maxY, first.bed.maxZ], [180, 180, 180]);
  assert.equal(first.objects.length, 1);
  assert.equal(first.objects[0].name, 'Block A');
  assert.deepEqual(first.objects[0].bbox, [20, 30, 0, 30, 40, 10]);
  // Duplicate vertices are merged, so the 12-face box keeps only 8 vertices.
  assert.equal(first.objects[0].vertices.length / 3, 8);
  assert.equal(first.objects[0].triangles, 12);

  const second = readPlateMesh(file, 'plated.3mf', 2);
  assert.equal(second.objects.length, 1);
  assert.equal(second.objects[0].name, 'Block B');
  assert.deepEqual(second.objects[0].bbox, [60, 60, 0, 70, 70, 10]);
});

test('packMesh packs correctly: the JSON header, then vertices and indices per object', () => {
  const mesh = readPlateMesh(platedFile('packed.3mf'), 'packed.3mf', 1);
  const buffer = packMesh(mesh);

  const length = buffer.readUInt32LE(0);
  const header = JSON.parse(buffer.subarray(4, 4 + length).toString('utf8'));
  assert.equal(header.objects.length, 1);
  assert.equal(header.objects[0].vertexCount, 8);
  assert.equal(header.objects[0].indexCount, 36);

  const at = 4 + Math.ceil(length / 4) * 4;
  const vertices = new Float32Array(buffer.buffer, buffer.byteOffset + at, 24);
  const indices = new Uint32Array(buffer.buffer, buffer.byteOffset + at + 96, 36);
  assert.deepEqual([...vertices.slice(0, 3)], [20, 30, 0]);
  assert.equal(Math.max(...indices), 7);
  assert.equal(buffer.length, at + 96 + 144);
});

test('STL mesh: a single object and no bed data', () => {
  const triangles = MESH_FACES.map((face) => face.map((corner) => MESH_CORNERS[corner]));
  const stl = Buffer.alloc(84 + triangles.length * 50);
  stl.writeUInt32LE(triangles.length, 80);
  triangles.forEach((triangle, index) => {
    const offset = 84 + index * 50 + 12;
    triangle.flat().forEach((value, item) => stl.writeFloatLE(value, offset + item * 4));
  });

  const mesh = readPlateMesh(write('solo.stl', stl), 'solo.stl', 1);
  assert.equal(mesh.bed, null);
  assert.equal(mesh.objects.length, 1);
  assert.equal(mesh.objects[0].name, 'solo.stl');
  assert.deepEqual(mesh.objects[0].bbox, [0, 0, 0, 10, 10, 10]);
});

