const dir = mkdtempSync(path.join(tmpdir(), 'p3d-meta-'));
const PNG = Buffer.from('89504e470d0a1a0a0000000d4948445200000001000000010806000000', 'hex');

function write(name, content) {
  const file = path.join(dir, name);
  writeFileSync(file, content);
  return file;
}

test('parseDuration understands slicer time formats', () => {
  assert.equal(parseDuration('1h 2m 3s'), 3723);
  assert.equal(parseDuration('12m 30s'), 750);
  assert.equal(parseDuration('1d 2h 0m 0s'), 93600);
  assert.equal(parseDuration('3600'), 3600);
  assert.equal(parseDuration(undefined), null);
});

